#!/usr/bin/env python3
"""Mutation testing for the Neesil VIP regressions.

Each block has a mutants.txt listing realistic RTL bugs. For every mutant this script
copies the RTL, injects the bug, reruns the block's checks (simulation and/or formal) and
records whether the checks caught it. A mutant that survives is a hole in the verification.

    python3 tools/mutate.py                # all blocks
    python3 tools/mutate.py apb uart       # some blocks
    python3 tools/mutate.py --report docs/MUTATION_REPORT.md
"""
import argparse
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# block -> (rtl file, [(check name, make dir, extra make args)])
BLOCKS = {
    "apb":      ("apb/rtl/apb_regfile.v",       [("sim", "apb/tb", [])]),
    "axi4lite": ("axi4lite/rtl/axil_regfile.v", [("sim", "axi4lite/tb", []),
                                                 ("formal", "axi4lite/formal", ["bmc", "prove"])]),
    "fifo":     ("fifo/rtl/sync_fifo.v",        [("formal", "fifo/formal", ["bmc", "prove"])]),
    "uart":     ("uart/rtl/uart.v",             [("sim", "uart/tb", [])]),
    "spi":      ("spi/rtl/spi_master.v",        [("sim", "spi/tb", [])]),
}
TIMEOUT = 300


def parse(path):
    out = []
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        mid, desc, find, repl = [x.strip() for x in line.split("|", 3)]
        out.append((mid, desc, find.replace("\\n", "\n"), repl.replace("\\n", "\n")))
    return out


def run_check(kind, mdir, targets, rtl, work):
    """Return True if the check PASSED (i.e. did not detect a problem)."""
    if kind == "sim":
        results = work / "results.xml"
        cmd = ["make", "-C", str(ROOT / mdir), f"RTL={rtl}", f"SIM_BUILD={work / 'sim_build'}",
               f"COCOTB_RESULTS_FILE={results}", "SEED=1"]
    else:
        cmd = ["make", "-C", str(ROOT / mdir), f"RTL={rtl}", f"BUILD={work / 'formal'}"] + targets
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=TIMEOUT)
    except subprocess.TimeoutExpired:
        return False, "timeout"
    if p.returncode != 0:
        return False, "fail"
    if kind == "sim":
        if not results.exists():
            return False, "no results"
        x = results.read_text()
        if "<failure" in x or "<error" in x:
            return False, "fail"
    return True, "pass"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("blocks", nargs="*", default=list(BLOCKS))
    ap.add_argument("--report", type=Path)
    args = ap.parse_args()

    rows, total, killed = [], 0, 0
    for blk in args.blocks:
        rtl_rel, checks = BLOCKS[blk]
        rtl = ROOT / rtl_rel
        src = rtl.read_text()
        mutants = parse(ROOT / blk / "mutants.txt")
        with tempfile.TemporaryDirectory() as td:
            base = Path(td) / "golden"
            base.mkdir()
            for kind, mdir, tg in checks:
                ok, why = run_check(kind, mdir, tg, rtl, base)
                if not ok:
                    sys.exit(f"{blk}: unmodified RTL does not pass its {kind} check ({why})")
        print(f"== {blk}: golden RTL passes, {len(mutants)} mutants")
        for mid, desc, find, repl in mutants:
            n = src.count(find)
            if n != 1:
                sys.exit(f"{blk}/{mid}: pattern found {n} times, expected exactly once")
            with tempfile.TemporaryDirectory() as td:
                work = Path(td)
                mrtl = work / rtl.name
                mrtl.write_text(src.replace(find, repl))
                caught = []
                t0 = time.time()
                for kind, mdir, tg in checks:
                    ok, why = run_check(kind, mdir, tg, mrtl, work / kind)
                    (work / kind).mkdir(exist_ok=True)
                    if not ok:
                        caught.append(f"{kind} ({why})" if why != "fail" else kind)
                dt = time.time() - t0
            total += 1
            killed += bool(caught)
            verdict = "caught by " + " + ".join(caught) if caught else "SURVIVED"
            print(f"   {mid:13s} {verdict:28s} {dt:5.1f}s  {desc}")
            rows.append((blk, mid, desc, verdict))
    score = 100.0 * killed / total if total else 0
    print(f"\nmutation score: {killed}/{total} = {score:.0f}%")
    if args.report:
        lines = ["# Mutation testing report", "",
                 "Generated by `python3 tools/mutate.py`. Each row is a realistic bug injected into the RTL;",
                 "the regression must fail for it to count as caught.", "",
                 f"**Mutation score: {killed}/{total} ({score:.0f}%)**", "",
                 "| Block | Mutant | Bug injected | Result |", "|---|---|---|---|"]
        lines += [f"| {b} | `{m}` | {d} | {v} |" for b, m, d, v in rows]
        lines += ["", "Simulation runs use SEED=1. Formal runs are BMC plus k-induction.",
                  "Reproduce with `python3 tools/mutate.py --report docs/MUTATION_REPORT.md`."]
        args.report.write_text("\n".join(lines) + "\n")
    sys.exit(0 if killed == total else 1)


if __name__ == "__main__":
    main()
